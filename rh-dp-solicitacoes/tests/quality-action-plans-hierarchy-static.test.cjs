const fs = require('fs')
const assert = require('assert')
const read = (p) => fs.readFileSync(p, 'utf8')
const schema = read('prisma/schema.prisma')
const migration = read('prisma/migrations/202607070001_quality_action_plan_hierarchy/migration.sql')
const client = read('src/app/dashboard/sst/planos-de-acao/PlanosDeAcaoClient.tsx')
const detail = read('src/app/dashboard/sst/planos-de-acao/[planId]/PlanoAvulsoDetailClient.tsx')
