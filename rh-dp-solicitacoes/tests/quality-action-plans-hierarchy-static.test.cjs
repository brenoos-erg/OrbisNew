const actionListRoute = read('src/app/api/sst/planos-de-acao/[planId]/acoes/route.ts')
const actionItemRoute = read('src/app/api/sst/planos-de-acao/[planId]/acoes/[actionId]/route.ts')
const ncRoute = read('src/app/api/sst/nao-conformidades/[id]/plano-de-acao/route.ts')
assert.match(schema, /model QualityActionPlan\s*\{/)
assert.match(schema, /model QualityActionPlanSequence\s*\{/)
assert.match(schema, /enum QualityActionPlanStatus\s*\{/)
assert.match(schema, /qualityActionPlanId\s+String\?/)
assert.match(schema, /nonConformityId\s+String\?/)
assert.match(migration, /GROUP BY `groupKey`, `numeroPlano`/, 'migração deve agrupar legados por referência')
assert.match(migration, /UPDATE `NonConformityActionItem` ai[\s\S]*qualityActionPlanId/, 'migração deve vincular ações ao plano pai')
assert.match(migration, /QualityActionPlanSequence[\s\S]*GREATEST/, 'migração deve avançar sequência para evitar número repetido')
assert.match(client, /\/api\/sst\/planos-de-acao/)
assert.match(client, /type PlanRow/)
assert.doesNotMatch(client, /type ActionRow/)
assert.match(client, /Planos de ação avulsos/)
assert.match(client, /Registrar plano de ação/)
assert.match(client, /Qtde de ações/)
assert.match(client, /% concluído/)
assert.match(client, /Exibir \/ Editar/)
assert.doesNotMatch(client, /<h1[^>]*>Ações do plano de ação/)
assert.match(menu, /Não conformidades/)
assert.match(menu, /Planos de ação avulsos/)
